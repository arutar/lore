const dictionaries: Record<Language, Record<Key, string>> = { ru, en };

export type Translate = (key: Key, values?: Record<string, string | number>) => string;

export function translator(language: Language): Translate {
  const dictionary = dictionaries[language] ?? ru;
  return (key, values) => {
    let text = dictionary[key] ?? ru[key] ?? key;
    for (const [name, value] of Object.entries(values ?? {})) text = text.replaceAll(`{${name}}`, String(value));
    return text;
  };
}

export interface Locale {
  language: Language;
  t: Translate;
  /** "5 minutes ago" style text for a timestamp. */
  ago: (iso?: string) => string;
  dateTime: (iso: string) => string;
  /** The message for a failed request, translated by its server error code when known. */
  error: (cause: unknown) => string;
}

export function makeLocale(language: Language): Locale {
  const t = translator(language);
  const relative = new Intl.RelativeTimeFormat(language, { numeric: "auto" });
  const steps: [Intl.RelativeTimeFormatUnit, number][] = [["year", 31536000], ["month", 2592000], ["week", 604800], ["day", 86400], ["hour", 3600], ["minute", 60]];
  return {
    language,
    t,
    ago: (iso) => {
      if (!iso) return t("common.never");
      const seconds = (new Date(iso).getTime() - Date.now()) / 1000;
      for (const [unit, size] of steps) if (Math.abs(seconds) >= size) return relative.format(Math.round(seconds / size), unit);
      return relative.format(Math.round(seconds), "second");
    },
    dateTime: (iso) => new Date(iso).toLocaleString(language, { dateStyle: "medium", timeStyle: "short" }),
    error: (cause) => {
      if (cause instanceof ApiError) {
        const key = `error.${cause.code}` as Key;
        return key in ru ? t(key) : cause.message;
      }
      return cause instanceof Error && cause.message ? cause.message : t("error.unknown");
    },
  };
}

export const LocaleContext = createContext<Locale>(makeLocale("en"));
export const useLocale = () => useContext(LocaleContext);
